def _e(x) -> str:
    return html.escape("" if x is None else str(x))


def _n(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def _pct(v) -> str:
    return "-" if v is None else f"{v * 100:.0f}%"


def _link(key: str) -> str:
    from integrations.tracker import issue_url
    url = issue_url(key) if key and key not in ("-", "(not traced)") else None
    return f'<a href="{_e(url)}">{_e(key)}</a>' if url else _e(key)


def _page(title: str, body: str, extra_head: str = "") -> str:
    return (f"<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            f"<meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>{_e(title)}</title><style>{_CSS}</style>{extra_head}</head><body>{body}</body></html>")


def _allure_href(data: dict) -> str:
    """The published Allure report: absolute when the site's address is known,
    so the copy kept on the store branch (and synced to a folder) links to it."""
    base = data.get("site_url") or ""
    return (base.rstrip("/") + "/allure/index.html") if base else "allure/index.html"


def _pdf_href(data: dict) -> str:
    """The PDF with its build time in the query: a phone's browser opened a
    cached PDF a day old (14 Nov 2026: 'Generated 2026-11-13 17:12', no
    defect section) - a new build is a new address, so never a stale copy."""
    stamp = "".join(ch for ch in str(data.get("generated") or "") if ch.isdigit())
    return f"summary.pdf?v={stamp}" if stamp else "summary.pdf"


def _header(data: dict, active: str) -> str:
    links = [("index.html", "Latest run"), ("history.html", "History"),
             (_allure_href(data), "Allure report"), ("traceability.html", "Traceability"),
             (_pdf_href(data), "PDF summary")]
    nav = "".join(f'<a href="{_e(h)}"{" aria-current=page" if h == active else ""}>{t}</a>'
                  for h, t in links)
    return (f"<header><h1>Test automation reports</h1><p>Generated {_e(data['generated'])} UTC "
            f"from {_e(data.get('source') or SOURCE_CI)}; history covers the last "
            f"{_e(data['window_days'])} days.</p><nav style='margin-top:10px'>{nav}</nav></header>")


_VERDICT_TEXT = {"failed": "failed", "outage": "not judged (application unavailable)",
                 "flaky": "flaky (passed on the retry)", "skipped": "skipped"}


def latest_html(data: dict) -> str:
    """The newest recorded run: what failed, flaked or could not be judged."""
    lr = data.get("latest")
    if not lr:
        body = "<p class='muted'>No run recorded yet.</p>"
    else:
        run = lr["run"]
        when = (run.get("started") or "")[:16].replace("T", " ")
        counts = (f"{run.get('passed', 0)} passed, {run.get('flaky', 0)} flaky, "
                  f"{run.get('failed', 0)} failed, {run.get('outage', 0)} not judged, "
                  f"{run.get('skipped', 0)} skipped")
        head = (f"<div class='grid'>"
                f"<div class='card kpi'><b>{_pct(lr['pass_rate'])}</b><span>pass rate</span></div>"
                f"<div class='card kpi'><b>{_e(run.get('failed', 0))}</b><span>failed</span></div>"
                f"<div class='card kpi'><b>{_e(run.get('flaky', 0))}</b><span>flaky</span></div>"
                f"<div class='card kpi'><b>{_e(run.get('outage', 0))}</b><span>not judged</span></div>"
                f"<div class='card kpi'><b>{round((run.get('duration_s') or 0) / 60, 1)}</b>"
                f"<span>minutes</span></div></div>"
                f"<p>Run <a href='{_e(run.get('url'))}'>{_e(run.get('run_id'))}</a>, {_e(when)} UTC "
                f"({_e(run.get('event'))}, commit <code>{_e((run.get('commit') or '')[:7])}</code>): "
                f"{_e(counts)}. <a href='{_e(_allure_href(data))}'>Steps, screenshots and traces in "
                f"the Allure report</a>.</p>")
        if lr["rows"]:
            table = _table(["Result", "Scenario", "Story", "Test case", "Error", "Seconds"], [[
                f"<span class='v-{_e(r['verdict'])}'>{_e(_VERDICT_TEXT.get(r['verdict'], r['verdict']))}</span>",
                f"{_e(r.get('scenario'))}<br><span class='muted'>{_e(r.get('file'))}</span>",
                _link(r.get("story") or "-"), _link(r.get("test_case") or "-"),
                f"<code>{_e(r.get('failure') or r.get('first_failure') or '')}</code>",
                _e(r.get("duration_s"))] for r in lr["rows"]])
            rest = (f"<p class='muted'>The other {_n(lr['passed'], 'test')} passed.</p>")
        else:
            table, rest = "", f"<p>All {_n(lr['passed'], 'test')} passed.</p>"
        body = (head + "<div class='card'><h2>Needs a look</h2>" + (table or "") + rest + "</div>")
    return _page("Latest run", _header(data, "index.html") + f"<main>{body}</main>")


def _table(head, rows) -> str:
    th = "".join(f"<th>{_e(h)}</th>" for h in head)
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f"<div class='wrap'><table><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>"


def dashboard_html(data: dict) -> str:
    k = data["kpis"]
    latest = k.get("latest_run") or {}
    cards = [
        (_pct(k["latest_pass_rate"]), "pass rate, latest run"),
        (_pct(k["window_pass_rate"]), "pass rate, window"),
        (k["runs"], "runs in the window"),
        ((latest or {}).get("tests", k["tests"]), "tests in the latest run"),
        (k["flaky"], "flaky passes"),
        (data["defects"]["total"] if data["defects"] else "-", "open defects"),
    ]
    kpi = "".join(f"<div class='card kpi'><b>{_e(v)}</b><span>{_e(t)}</span></div>" for v, t in cards)
    last = (f"<p class='muted'><a href='index.html'>Latest run</a>: <a href='{_e(latest.get('url'))}'>{_e(latest.get('run_id'))}</a> "
            f"({_e((latest.get('started') or '')[:16].replace('T', ' '))}, {_e(latest.get('event'))}) - "
            f"{latest.get('passed', 0)} passed, {latest.get('flaky', 0)} flaky, {latest.get('failed', 0)} failed, "
            f"{latest.get('outage', 0)} outage, {latest.get('skipped', 0)} skipped.</p>") if latest else \
        "<p class='muted'>No run recorded in the window yet.</p>"
    slow = _table(["Test", "Median s", "Max s", "Runs"],
                  [[f"<code>{_e(r['test'])}</code>", r["median_s"], r["max_s"], r["runs"]]
                   for r in data["slowest"]])
    flaky = _table(["Test", "Flaky", "Runs", "Last"],
                   [[f"<code>{_e(r['test'])}</code>", r["flaky"], r["runs"], _e(r["last"])]
                    for r in data["flaky"]]) if data["flaky"] else "<p class='muted'>No flaky pass in the window.</p>"

    def bd(rows):
        return _table(["Name", "Tests", "Passed", "Failed", "Other", "Pass rate"],
                      [[_link(r["name"]) if r["name"].count("-") == 1 and r["name"].split("-")[-1].isdigit()
                        else _e(r["name"]), r["tests"], r["passed"], r["failed"], r["other"],
                        _pct(r["pass_rate"])] for r in rows])
    if data["defects"] is None:
        defects = "<p class='muted'>The tracker could not be read: no defect figures.</p>"
    elif not data["defects"]["total"]:
        defects = "<p class='muted'>No open defect.</p>"
    else:
        defects = ("<div id='defects-age'></div>" + _table(
            ["Defect", "Summary", "Status", "Created", "Components"],
            [[_link(d["key"]), _e(d["summary"]), _e(d["status"]), _e((d.get("created") or "")[:10]),
              _e(", ".join(d.get("components") or []) or "-")] for d in data["defect_list"]]))
    body = (_header(data, "history.html") + "<main>" + f"<div class='grid'>{kpi}</div>" + last
            + "<div class='card'><h2>Results per run</h2><div id='trend'></div></div>"
            + "<div class='card'><h2>Suite duration per run (minutes)</h2><div id='duration'></div></div>"
            + f"<div class='card'><h2>Slowest tests (median over the window)</h2>{slow}</div>"
            + f"<div class='card'><h2>Flaky tests</h2>{flaky}</div>"
            + f"<div class='card'><h2>By feature file (latest result of each test)</h2>{bd(data['by_file'])}</div>"
            + f"<div class='card'><h2>By story</h2>{bd(data['by_story'])}</div>"
            + f"<div class='card'><h2>Open defects</h2>{defects}</div>"
            + defect_history_html(data) + "</main>")
    t = data["trend"]
    ids = [str(r) for r in t["run"]]
    series = [{"type": "bar", "name": k, "x": ids, "y": t[k], "marker": {"color": c},
               "hovertext": [f"run {i}, {s}" for i, s in zip(ids, t["started"])]}
              for k, c in COLORS.items()]
    age = (data["defects"] or {}).get("by_age") or []
    script = (f"<script src='{PLOTLY}'></script><script>"
              # On a phone a finger dragging over a chart zoomed it (14 Nov
              # 2026: the defect trend showed 5 of its 30 days and y 0.4-1):
              # no drag or scroll zoom, fixed axes, counts from 0.
              f"const C={PLOT_CONFIG};"
              f"const L={{barmode:'stack',margin:{{t:30,r:10,b:90,l:40}},height:340,bargap:0.3,legend:{{orientation:'h',y:1.12}},"
              f"dragmode:false,yaxis:{{rangemode:'tozero',fixedrange:true}},"
              f"paper_bgcolor:'rgba(0,0,0,0)',plot_bgcolor:'rgba(0,0,0,0)',xaxis:{{type:'category',fixedrange:true}}}};"
              # One bar per run: two runs started in the same minute share a
              # label, so the axis is the run id and the label the start time.
              f"const X=Object.assign({{}},L,{{xaxis:{{type:'category',fixedrange:true,tickvals:{json.dumps([str(r) for r in t['run']])},"
              f"ticktext:{json.dumps(t['started'])}}}}});"
              f"if(window.Plotly){{Plotly.newPlot('trend',{json.dumps(series)},X,C);"
              f"Plotly.newPlot('duration',[{{type:'scatter',mode:'lines+markers',x:{json.dumps(ids)},"
              f"y:{json.dumps(t['duration_min'])},name:'minutes'}}],Object.assign({{}},X,{{barmode:null}}),C);"
              + (f"Plotly.newPlot('defects-age',[{{type:'bar',x:{json.dumps([a for a, _ in age])},"
                 f"y:{json.dumps([n for _, n in age])},marker:{{color:'#c62828'}}}}],"
                 f"Object.assign({{}},L,{{height:220}}),C);" if age else "")
              + _defect_trend_js(data)
              + "}</script>")
    return _page("Test history", body + script)


def defect_history_html(data: dict) -> str:
    """RP12: the defect trend, totals, density per module and per sprint."""
    h = data.get("defect_history")
    if not h:
        return ("<div class='card'><h2>Defects over time</h2><p class='muted'>No defect "
                "history yet: it starts with the first build that reads the tracker.</p></div>")
    sm = h["summary"]
    cards = [(sm["opened"], "defects opened"), (sm["closed"], "closed"),
             (sm["open"], "open now"),
             ("-" if sm["mean_days_to_close"] is None else sm["mean_days_to_close"],
              "mean days to close"),
             (sm["reopened"], "reopened"), (sm["deleted"], "deleted from the tracker"),
             (_share(sm.get("detection_rate")), "found by the pipeline")]
    kpi = "".join(f"<div class='card kpi'><b>{_e(v)}</b><span>{_e(t)}</span></div>"
                  for v, t in cards)
    cats = ", ".join(f"{n} {c}" for c, n in sm["closed_by_category"]) or "none closed"
    who = f"{sm['by_pipeline']} raised by the pipeline, {sm['by_person']} by a person"
    mods = _table(["Module", "Scenarios", "Opened", "Found by the pipeline",
                   "Found by a person", "Detection rate", "Product defects", "Closed",
                   "Open now", f"Density (per {h['per']} scenarios)"],
                  [[_e(r["module"]), r["scenarios"], r["opened"], r.get("by_pipeline", 0),
                    r.get("by_person", 0), _e(_share(r.get("detection_rate"))), r["product"],
                    r["closed"], r["open"], "-" if r["density"] is None else r["density"]]
                   for r in h["modules"]])
    sprints = _table(["Sprint", "From", "To", "Opened", "Found by the pipeline",
                      "Found by a person", "Closed", "Open at the record",
                      "Mean days to close", "Densest module"],
                     [[_e(sp["name"]), _e(sp["start"]), _e(sp["end"]), _e(sp["opened"]),
                       _e(sp.get("by_pipeline") if sp.get("by_pipeline") is not None else "-"),
                       _e(sp.get("by_person") if sp.get("by_person") is not None else "-"),
                       _e(sp["closed"]), _e(sp["open"]),
                       _e("-" if sp["mean_days_to_close"] is None else sp["mean_days_to_close"]),
                       _e(f"{sp['densest']['module']} ({sp['densest']['density']})"
                          if sp.get("densest") else "-")] for sp in h["sprints"]]) \
        if h["sprints"] else "<p class='muted'>No sprint recorded yet.</p>"
    return (f"<div class='card'><h2>Defects over time (last {_e(data['window_days'])} days)</h2>"
            f"<div class='grid'>{kpi}</div>"
            f"<p class='muted'>Opened: {_e(who)}. Closed as: {_e(cats)}. Kept on the results "
            f"store ({_e(h['recorded'])} defects), so a defect closed or deleted in the tracker "
            f"stays in these figures.</p><div id='defect-trend'></div></div>"
            f"<div class='card'><h2>Defect density by module</h2>{mods}<p class='muted'>Product "
            f"defects opened in the window per {_e(h['per'])} scenarios of the module. A defect "
            f"closed as test, environment, duplicate or not-a-bug is left out; one not yet "
            f"categorised is counted. Module: the defect's tracker component, else its test's "
            f"feature file (<code>reporting.modules</code>). Found by the pipeline: the nightly "
            f"run's triage raised it (its label or its triage data); by a person: anyone else "
            f"- manual testing, acceptance, production. The detection rate is the pipeline's "
            f"share: a low one in a module points at tests that are missing.</p></div>"
            f"<div class='card'><h2>Defects per sprint</h2>{sprints}</div>")


def _share(value) -> str:
    """A share already in percent (the detection rate): 66.7 -> '66.7%'.
    Not _pct, which takes a fraction (a pass rate): 0.99 -> '99%'."""
    return "-" if value is None else f"{value:g}%"


def _defect_trend_js(data: dict) -> str:
    h = data.get("defect_history")
    if not h:
        return ""
    t = h["trend"]
    series = [{"type": "bar", "name": "opened", "x": t["days"], "y": t["opened"],
               "marker": {"color": COLORS["failed"]}},
              {"type": "bar", "name": "closed", "x": t["days"], "y": t["closed"],
               "marker": {"color": COLORS["passed"]}},
              {"type": "scatter", "mode": "lines", "name": "open", "x": t["days"],
               "y": t["open"], "line": {"color": "#1f4e8c", "width": 2}}]
    top = max([1] + t["opened"] + t["closed"] + t["open"])
    # Whole days and whole defects: the axes never zoom to a part of the
    # window, and an all-zero window still shows 0 at the bottom.
    return (f"Plotly.newPlot('defect-trend',{json.dumps(series)},Object.assign({{}},L,"
            f"{{barmode:'group',height:300,xaxis:{{type:'date',fixedrange:true,"
            f"range:{json.dumps([t['days'][0], t['days'][-1]])}}},"
            f"yaxis:{{rangemode:'tozero',fixedrange:true,tickformat:',d',dtick:{-(-top // 5)},"
            f"range:[0,{top}]}}}}),C);")


def _test_case_cell(r: dict) -> str:
    """A real gap (a mapped criterion no test case covers) in red; a test
    case only when there is one - never 'none' where nothing is known."""
    if r["test_case"]:
        note = f"<br><span class='muted'><i>{_e(r['note'])}</i></span>" if r.get("note") else ""
        return (f"{_link(r['test_case'])}<br><span class='muted'>"
                f"{_e(r['test_case_summary'])}</span>{note}")
    if r["result"] == "no test case" and r["criterion"] != "-":
        return "<span class='v-failed'>none</span>"
    if r["result"] == "cited test case not found":
        return "<span class='v-failed'>cited title not found</span>"
    return "-"


def traceability_html(data: dict) -> str:
    rows = data["traceability"]
    if rows is None:
        body = "<p class='muted'>The tracker could not be read: no traceability matrix.</p>"
    else:
        sm = data["traceability_summary"]
        res = ", ".join(f"{n} {k}" for k, n in sorted(sm["results"].items())) or "none"
        unmapped = (f"; {sm['criteria_unmapped']} on stories Agent 1 left no coverage map for"
                    if sm.get("criteria_unmapped") else "")
        head = (f"<p>{_n(sm['stories'], 'story').replace('storys', 'stories')}, "
                f"{_n(sm['criteria'], 'acceptance criterion').replace('criterions', 'criteria')} "
                f"({sm['criteria_uncovered']} without a test case{unmapped}), "
                f"{_n(sm['test_cases'], 'test case')} "
                f"({sm['test_cases_without_scenario']} without a scenario on the default branch). "
                f"Scenario results: {res}.</p>")
        body = head + _table(
            ["Story", "Criterion", "Test case", "Scenario", "Last result", "Defects"],
            [[f"{_link(r['story'])}<br><span class='muted'>{_e(r['story_summary'])}</span>",
              (f"<b>{_e(r['criterion'])}</b> " if r["criterion"] != "-" else "")
              + (f"<span class='muted'>{_e(r['criterion_text'])}</span>" if r["criterion"] == "-"
                 else _e(r["criterion_text"])),
              _test_case_cell(r),
              f"<code>{_e(r['scenario'].split('::')[-1])}</code>" if r["scenario"] else "-",
              f"<span class='v-{_e(r['result'])}'>{_e(r['result'])}</span> {_e(r['result_date'])}",
              " ".join(_link(d) for d in r["defects"]) or "-"] for r in rows])
        loose = data.get("unlinked_defects") or []
        if loose:
            body += ("<h2 style='margin-top:20px'>Open defects not linked to a story or test "
                     "case here</h2><p class='muted'>Raised without a link (or linked to an issue "
                     "outside this matrix), so no row can show them. Link each to its test case "
                     "or story to place it.</p>" + _table(
                         ["Defect", "Summary", "Status", "Created"],
                         [[_link(d["key"]), _e(d.get("summary")), _e(d.get("status")),
                           _e((d.get("created") or "")[:10])] for d in loose]))
    return _page("Traceability", _header(data, "traceability.html")
                 + f"<main><div class='card'><h2>Traceability matrix</h2>{body}</div></main>")


