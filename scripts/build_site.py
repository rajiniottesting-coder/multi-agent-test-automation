def _trend_png(data: dict, path: Path) -> bool:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    t = data["trend"]
    if not t["run"]:
        return False
    fig, ax = plt.subplots(figsize=(7, 2.6), dpi=150)
    bottom = [0] * len(t["run"])
    x = list(range(len(t["run"])))
    for k, c in COLORS.items():
        ax.bar(x, t[k], bottom=bottom, color=c, label=k, width=0.7)
        bottom = [b + v for b, v in zip(bottom, t[k])]
    ax.set_xticks(x, [s[5:10] for s in t["started"]], rotation=45, fontsize=7)
    ax.set_ylabel("tests", fontsize=8)
    ax.legend(fontsize=7, ncol=5, loc="upper center", bbox_to_anchor=(0.5, 1.22), frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return True


def summary_pdf(data: dict, path: Path, sprint_end: bool) -> bool:
    """The management summary. False when ReportLab is not installed."""
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib.units import cm
        from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    except ImportError:
        logger.warning("reportlab not installed: no PDF summary")
        return False
    st = getSampleStyleSheet()
    k = data["kpis"]
    latest = k.get("latest_run") or {}
    sprint = data.get("sprint") or {}
    title = ("Sprint test summary - " + sprint.get("name", "") if sprint_end
             else "Test automation summary")
    flow = [Paragraph(title, st["Title"]),
            Paragraph(f"Generated {data['generated']} UTC; window: last {data['window_days']} days"
                      + (f"; {sprint.get('name')} ends {str(sprint.get('end') or '')[:10]}"
                         if sprint else ""), st["Normal"]), Spacer(1, 0.4 * cm)]
    rows = [["Measure", "Value"],
            ["Pass rate, latest run", _pct(k["latest_pass_rate"])],
            ["Pass rate, window", _pct(k["window_pass_rate"])],
            ["Runs in the window", str(k["runs"])],
            ["Tests in the latest run", str(latest.get("tests", k["tests"]))],
            ["Flaky passes", str(k["flaky"])],
            ["Open defects", str(data["defects"]["total"]) if data["defects"] else "not read"]]
    if latest:
        rows.append(["Latest run", f"{latest.get('run_id')} ({(latest.get('started') or '')[:10]}): "
                     f"{latest.get('passed', 0)} passed, {latest.get('flaky', 0)} flaky, "
                     f"{latest.get('failed', 0)} failed, {latest.get('outage', 0)} outage"])
    style = TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f4e8c")),
                        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c8ccd2")),
                        ("FONTSIZE", (0, 0), (-1, -1), 9), ("VALIGN", (0, 0), (-1, -1), "TOP")])
    flow += [Table(rows, colWidths=[6 * cm, 10.5 * cm], style=style), Spacer(1, 0.5 * cm)]
    png = path.with_suffix(".png")
    if _trend_png(data, png):
        flow += [Paragraph("Results per run", st["Heading2"]), Image(str(png), width=17 * cm,
                                                                     height=6.3 * cm)]
    if data["defects"] and data["defects"]["total"]:
        flow += [Paragraph("Open defects by age", st["Heading2"]),
                 Table([["Age", "Defects"]] + [[a, str(n)] for a, n in data["defects"]["by_age"]],
                       colWidths=[6 * cm, 4 * cm], style=style)]
    failing = [r for r in data["by_file"] if r["failed"]]
    flow += [Paragraph("Risks", st["Heading2"])]
    risks = [f"{r['name']}: {r['failed']} failing of {r['tests']}" for r in failing]
    risks += [f"{r['test']} flaked {r['flaky']} times in {r['runs']} runs" for r in data["flaky"][:5]]
    if data.get("traceability_summary"):
        sm = data["traceability_summary"]
        if sm["criteria_uncovered"]:
            risks.append(f"{sm['criteria_uncovered']} acceptance criteria have no test case")
    for r in risks or ["None found in the window."]:
        flow.append(Paragraph("&bull; " + html.escape(r), st["Normal"]))
    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                      topMargin=1.6 * cm, bottomMargin=1.6 * cm, title=title).build(flow)
    png.unlink(missing_ok=True)
    return True


def is_sprint_last_day(sprint: dict | None, now: _dt.datetime) -> bool:
    end = (sprint or {}).get("end")
    if not end:
        return False
    try:
        t = _dt.datetime.fromisoformat(str(end).replace("Z", "+00:00"))
    except ValueError:
        return False
    if t.tzinfo is None:
        t = t.replace(tzinfo=_dt.timezone.utc)
    return 0 <= (t - now).total_seconds() <= 24 * 3600


def keep_pdf(store: Path, pdf: Path, now: _dt.datetime, sprint_end: bool, keep: int) -> None:
    """A dated copy on the store; the oldest nightly copies beyond `keep` go
    (a sprint's last-day copy stays)."""
    folder = store / "pdf"
    folder.mkdir(parents=True, exist_ok=True)
    name = now.strftime("%Y-%m-%d") + ("-sprint-end" if sprint_end else "") + ".pdf"
    shutil.copyfile(pdf, folder / name)
    nightly = sorted(p for p in folder.glob("*.pdf") if "sprint-end" not in p.name)
    for old in nightly[:-keep] if keep > 0 else []:
        old.unlink()


def main(argv=None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--store", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--features", default=Path("features"), type=Path)
    ap.add_argument("--no-tracker", action="store_true")
    ap.add_argument("--site-url", default=None, help="where the site is published")
    ap.add_argument("--sprint-summary", choices=("auto", "force", "off"), default="auto",
                    help="record the sprint's summary on the tracker (RP7): on the "
                         "sprint's last day (auto), now (force), or never")
    args = ap.parse_args(argv)
    from core.ops_settings import section
    now = _dt.datetime.now(_dt.timezone.utc)
    try:
        data = collect(args.store, args.features, now, with_tracker=not args.no_tracker)
    except Exception as e:                                         # noqa: BLE001
        print(f"::error::Reports not built - the results store could not be read: {e}")
        return 1
    data["site_url"] = args.site_url
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "index.html").write_text(latest_html(data), encoding="utf-8")
    (args.out / "history.html").write_text(dashboard_html(data), encoding="utf-8")
    (args.out / "traceability.html").write_text(traceability_html(data), encoding="utf-8")
    (args.out / "data.json").write_text(json.dumps(data, default=str, indent=1), encoding="utf-8")
    sprint_end = is_sprint_last_day(data.get("sprint"), now)
    pdf = args.out / "summary.pdf"
    if summary_pdf(data, pdf, sprint_end):
        keep_pdf(args.store, pdf, now, sprint_end, int(section("reporting").get("pdf_keep") or 14))
    summary_key = None
    if not args.no_tracker and (args.sprint_summary == "force"
                                or (args.sprint_summary == "auto" and sprint_end)):
        from core.sprint_summary import post
        summary_key = post(_tracker(), data, pdf if pdf.exists() else None, args.site_url,
                           force=args.sprint_summary == "force")
    k = data["kpis"]
    print(f"Site built: {k['runs']} run(s), {k['tests']} test(s) in the window; "
          f"traceability {'built' if data['traceability'] is not None else 'not built'}; "
          f"PDF {'made' if pdf.exists() else 'not made'}{' (sprint end)' if sprint_end else ''}"
          f"{f'; sprint summary {summary_key}' if summary_key else ''}.")
    return 0


