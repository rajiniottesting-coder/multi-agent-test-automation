"""Build the reports site from the results store (RP3 dashboard, RP4
traceability matrix, RP6 PDF summary).

    python -m scripts.build_site --store store/ --out site/ [--features features]

Writes into --out:
  index.html          the latest run: what failed, flaked or could not be judged,
                      with the error, story and test case, and the run's link
  history.html        the dashboard: trend, durations, flaky tests, breakdowns,
                      open defects (Plotly, from a CDN)
  traceability.html   story -> acceptance criterion -> test case -> scenario ->
                      last result -> defect
  summary.pdf         the management summary (ReportLab); a dated copy is kept
                      on the store under pdf/ (`reporting.pdf_keep` of them,
                      and every one made on a sprint's last day)
  data.json           what the pages show, for anyone who wants the numbers

Only the results store and the tracker are read - no model is called. The
tracker is optional: without it the defect and traceability sections say so.
The Allure report is generated by the workflow into --out/allure/.
Exit 0 unless the store cannot be read at all.
"""
