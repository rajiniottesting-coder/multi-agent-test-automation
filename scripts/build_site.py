def _tracker():
    try:
        from integrations.tracker import get_tracker
        return get_tracker()
    except Exception as e:                                         # noqa: BLE001
        logger.info("Tracker not reachable (%s); defects and traceability left out.", e)
        return None


def open_defects(tracker) -> list[dict] | None:
    """Every open issue of the defect type - raised by the pipeline or by a
    person - or None when the tracker cannot say."""
    from core.defects import settings as defect_settings
    from integrations.tracker import capability
    from core.ops_settings import section
    read = capability(tracker, "issues_for_report") if tracker else None
    if read is None:
        return None
    # A throw-away issue (cleanup.delete_label) is no defect of the
    # application: left out here as in the defect history.
    throwaway = (section("cleanup").get("delete_label") or "").strip()
    return [d for d in read(defect_settings()["issue_type"], open_only=True)
            if not throwaway or throwaway not in (d.get("labels") or [])]


def _coverage_comment(comments: list) -> str:
    import re
    for body in reversed(comments or []):           # the newest map wins
        if re.match(r"\s*\\?\[agent1:coverage\\?\]", str(body)):
            return str(body)
    return ""


def _coverage(comment: str, refs: list, tcs: list) -> dict:
    """The coverage map, following titles revised since Agent 1 wrote it."""
    from core.report_data import coverage_map, reworded_matches, unmatched_citations
    coverage = coverage_map(comment, refs, tcs)
    reworded = reworded_matches(comment, refs, tcs)
    for ref, keys in reworded.items():
        coverage.setdefault(ref, []).extend(k for k in keys if k not in coverage[ref])
    return {"coverage": coverage,
            "reworded": {(ref, k) for ref, keys in reworded.items() for k in keys},
            "unmatched": unmatched_citations(comment, refs, tcs) - set(reworded)}


def traceability(tracker, features_dir: Path, latest: dict, defects: list[dict] | None) -> list[dict]:
    """The matrix rows (core.report_data.traceability_rows) for every story
    that owns a test case the suite implements."""
    from agents.agent2_coder import build_marker_index
    from core.acceptance_coverage import extract_criteria
    from core.report_data import traceability_rows
    index = build_marker_index(features_dir)
    scenarios: dict = {}
    for rec in latest.values():
        if rec.get("test_case"):
            scenarios.setdefault(rec["test_case"], []).append(rec["test"])
    owners: dict = {}                               # story -> test case keys
    for key, entry in index.by_key.items():
        owner = getattr(entry, "owner", None) or tracker.get_parent_story_key(key)
        if owner:
            owners.setdefault(owner, set()).add(key)
            scenarios.setdefault(key, [])
    defects_by_key: dict = {}
    for d in defects or []:
        for k in d.get("links") or []:
            defects_by_key.setdefault(k, []).append(d["key"])
    stories = []
    for key in sorted(owners, key=lambda k: (len(k), k)):
        try:
            story = tracker.get_story(key)
            tcs = tracker.get_linked_test_cases(key)
            comments = tracker.get_comments(key)
        except Exception as e:                                     # noqa: BLE001
            logger.warning("Story %s not read for the matrix: %s", key, e)
            continue
        criteria = [(c.ref, c.text) for c in extract_criteria(story.get("summary"),
                                                              story.get("description"))]
        # A test case the suite implements for this story is listed even when
        # the tracker no longer links it (13 Nov 2026, first live matrix: a
        # story's second test case was on main, marked for it, and missing).
        linked = {tc["key"] for tc in tcs}
        tcs = list(tcs) + [{"key": k, "summary": index.by_key[k].title}
                           for k in sorted(owners[key]) if k not in linked]
        comment = _coverage_comment(comments)
        refs = [r for r, _ in criteria]
        stories.append({**story, "criteria": criteria, "test_cases": tcs,
                        "has_coverage_map": bool(comment),
                        **_coverage(comment, refs, tcs),
                        "scenarios": {k: scenarios.get(k) or [] for k in
                                      {tc["key"] for tc in tcs} | owners[key]}})
    return traceability_rows(stories, latest, defects_by_key)


def collect(store: Path, features_dir: Path, now: _dt.datetime, with_tracker: bool = True) -> dict:
    from core import report_data as rd
    from core import results_store as rs
    from core.ops_settings import section
    s = section("reporting")
    since = (now - _dt.timedelta(days=int(s.get("window_days") or 30))).isoformat()
    runs = [r for r in rs.read_runs(store) if (r.get("started") or "") >= since]
    results = rs.read_results(store, since=since)
    latest = rs.latest_by_test(rs.read_results(store))
    current = ({r["test"] for r in results if r.get("run_id") == runs[-1]["run_id"]}
               if runs else None)                  # the suite as it is now
    tracker = _tracker() if with_tracker else None
    defects = open_defects(tracker) if tracker else None
    sprint = None
    if tracker is not None:
        from integrations.tracker import capability
        read = capability(tracker, "get_active_sprint")
        sprint = read() if read else None
    rows = None
    if tracker is not None:
        try:
            rows = traceability(tracker, features_dir, latest, defects)
        except Exception as e:                                     # noqa: BLE001
            logger.warning("Traceability matrix not built: %s", e)
    history = defect_history(store, tracker, features_dir, sprint, now)
    return {
        "generated": now.strftime("%Y-%m-%d %H:%M"), "window_days": s.get("window_days"),
        "kpis": rd.kpis(runs, results), "trend": rd.trend(runs),
        "latest": rd.latest_run(runs, results),
        "slowest": rd.slowest(results), "flaky": rd.flaky_ranking(results),
        "by_file": rd.breakdown(results, "file", current),
        "by_story": rd.breakdown(results, "story", current),
        "defects": rd.defects_summary(defects, now) if defects is not None else None,
        "defect_list": defects, "sprint": sprint,
        "traceability": rows,
        "traceability_summary": rd.traceability_summary(rows) if rows is not None else None,
        "unlinked_defects": (rd.unlinked_defects(defects, rows)
                             if rows is not None and defects is not None else None),
        "defect_history": defect_figures(history, now, int(s.get("window_days") or 30)),
    }


def defect_figures(history: dict, now: _dt.datetime, window_days: int) -> dict | None:
    """RP12: the window's defect trend, totals and density per module, and
    one row per recorded sprint - None only while the tracker was never read.
    A history that was read and holds no defect shows zeros: 14 Nov 2026 it
    read 'No defect history yet' once every defect had left it."""
    from core import defect_ledger as dl
    recs = history["records"]
    if not recs and not history.get("ever_synced"):
        return None
    end = now.astimezone(_dt.timezone.utc).date()
    start = end - _dt.timedelta(days=window_days - 1)
    a, b = start.isoformat(), end.isoformat()
    return {"summary": dl.summary(recs, a, b), "trend": dl.trend(recs, start, end),
            "modules": dl.by_module(recs, a, b, history["scenarios"], history["per"]),
            "per": history["per"], "recorded": len(recs), "sync": history["synced"],
            "sprints": [{k: sp.get(k) for k in ("name", "start", "end", "opened", "closed",
                                                 "open", "mean_days_to_close", "reopened",
                                                 "by_pipeline", "by_person", "detection_rate",
                                                 "written")}
                        | {"densest": next((m for m in sp.get("modules") or []
                                            if m.get("density")), None)}
                        for sp in history["sprints"]]}


def defect_history(store: Path, tracker, features_dir: Path, sprint: dict | None,
                   now: _dt.datetime) -> dict:
    """D7: bring the store's defect history up to date (when the tracker can
    be read) and record the active sprint's figures. The history is read
    from the store either way, so the pages show it without the tracker."""
    from core import defect_ledger as dl
    from core.ops_settings import section
    s = section("reporting")
    synced = None
    if tracker is not None:
        try:
            synced = dl.sync(store, tracker, features_dir, now)
        except Exception as e:                                     # noqa: BLE001
            logger.warning("Defect history not updated: %s", e)
    recs = dl.records(store)
    scenarios = dl.scenarios_per_module(features_dir, s.get("modules") or {})
    per = int(s.get("density_per") or 10)
    # Whenever the tracker was read - a sprint with no defect is a record too,
    # and one written before its throw-away defects left must be rewritten.
    if synced is not None:
        try:
            dl.sprint_snapshot(store, sprint, recs, scenarios, per, now)
        except Exception as e:                                     # noqa: BLE001
            logger.warning("Sprint defect record not written: %s", e)
    return {"synced": synced, "ever_synced": bool(dl.read(store).get("synced")),
            "records": recs, "scenarios": scenarios, "per": per,
            "sprints": dl.read_sprints(store)}


