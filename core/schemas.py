"""
Pydantic schemas for data flowing between agents.
These are the contracts — every agent reads/writes data matching these shapes.
"""
from typing import Literal, Optional
from pydantic import BaseModel, Field


# ─────────────────────────────────────────────────────────────
# Schemas for Agent 1 (Test Designer)
# ─────────────────────────────────────────────────────────────

class TestStep(BaseModel):
    """A single step inside a test case."""
    step_number: int = Field(..., description="1-indexed step order")
    action: str = Field(..., description="What the user does (e.g., 'Click Login button')")
    expected_result: str = Field(..., description="What should happen (e.g., 'User is logged in')")


class TestCase(BaseModel):
    """A manual test case generated by Agent 1 (Test Designer)."""
    title: str = Field(..., description="Concise test case title")
    description: str = Field(..., description="What this test verifies")
    priority: Literal["High", "Medium", "Low"] = Field(default="Medium")
    test_type: Literal["Positive", "Negative", "Edge"] = Field(default="Positive")
    preconditions: list[str] = Field(default_factory=list, description="Setup needed before test")
    steps: list[TestStep] = Field(..., description="Ordered test steps")
    expected_outcome: str = Field(..., description="Overall expected result")
    test_data: Optional[dict] = Field(default=None, description="Test data like usernames/passwords")


class TestCaseList(BaseModel):
    """A collection of test cases generated from one story."""
    story_summary: str = Field(..., description="Brief summary of the story analyzed")
    test_cases: list[TestCase] = Field(..., min_length=1, description="At least one test case")


class TestCaseRevision(BaseModel):
    """One approved, impacted test case rewritten for the change story."""
    key: str = Field(..., description="The existing test case key, exactly as given (e.g. 'PROJ-3')")
    revised: TestCase = Field(..., description="The full revised test case")
    change_note: str = Field(..., description="One line: what changed and why")


class ImpactAwareDraft(BaseModel):
    """Agent 1's output in impact-aware mode (Agent 0 design, C3)."""
    story_summary: str = Field(..., description="Brief summary of the story analyzed")
    revisions: list[TestCaseRevision] = Field(
        default_factory=list, description="Exactly one entry per approved test case")
    new_test_cases: list[TestCase] = Field(
        default_factory=list,
        description="Only for acceptance criteria no revised test case covers")


class ChangeSeeds(BaseModel):
    """Agent 0, stage 2 (requirement trigger): where a story's change lands."""
    change_type: Literal["new_behaviour", "changed_behaviour", "removed_behaviour", "mixed"] = Field(
        ..., description="What kind of change the story makes to EXISTING behaviour")
    behaviours: list[str] = Field(default_factory=list,
                                  description="Each existing behaviour the story changes, one short line each")
    element_keys: list[str] = Field(
        default_factory=list,
        description="Inventory elements the story names or clearly changes, as 'page:key' "
                    "exactly as they appear in the inventory")
    components: list[str] = Field(default_factory=list,
                                  description="Components the change touches")


class WordingChange(BaseModel):
    old: str = Field(..., description="The user-visible text as the application shows it TODAY, "
                                      "exactly, without surrounding quotes")
    new: str = Field(..., description="The text the story says it becomes, exactly, without quotes")


class WordingChanges(BaseModel):
    """Agent 0, context update: user-visible text a story replaces."""
    changes: list[WordingChange] = Field(
        default_factory=list,
        description="Each text replacement the story states explicitly. Empty when it states none")


class NoteRewrite(BaseModel):
    path: str = Field(..., description="The file the passage is in, exactly as given")
    old: str = Field(..., description="The passage copied VERBATIM from that file - a whole "
                                      "sentence, bullet or paragraph")
    new: str = Field(..., description="The passage rewritten to describe the application "
                                      "AFTER the change")
    reason: str = Field(..., description="The story sentence that makes the old passage untrue")


class NoteRewrites(BaseModel):
    """Agent 0, context update: reference passages a story makes untrue."""
    rewrites: list[NoteRewrite] = Field(
        default_factory=list,
        description="Each passage the story makes untrue. Empty when it makes none untrue")


class CandidateAssessment(BaseModel):
    candidate_id: str = Field(..., description="The candidate id exactly as given, e.g. 'C3'")
    tier: Literal["must-update", "review", "unaffected"] = Field(...)
    reason: str = Field(..., description="One or two sentences")
    evidence_refs: list[str] = Field(
        default_factory=list,
        description="Each item is EITHER a path id given for this candidate (e.g. 'P1') OR a "
                    "step quoted VERBATIM from the candidate's scenario")


class ImpactAssessment(BaseModel):
    """Agent 0, stage 5: the model's judgement of the short list."""
    assessments: list[CandidateAssessment] = Field(default_factory=list)


# ─────────────────────────────────────────────────────────────
# Schemas for Agent 2 (Coder) — TWO-STAGE APPROACH
# ─────────────────────────────────────────────────────────────

class FilePlan(BaseModel):
    """Stage 1 metadata for a file to be generated. NO actual content here."""
    file_path: str = Field(..., description="Project-relative file path (e.g., 'features/cart.feature')")
    file_type: Literal["feature", "step_definitions", "page_object", "other"] = Field(
        default="other",
        description="Kind of file: feature, step_definitions, page_object, or other"
    )
    is_new_file: bool = Field(default=True, description="True if creating new, False if updating existing")
    purpose: str = Field(..., description="One-sentence justification for this file")
    related_test_cases: list[str] = Field(
        default_factory=list,
        description="Jira test case keys this file addresses (e.g., ['PROJ-7', 'PROJ-9'])"
    )


class CodePlan(BaseModel):
    """Stage 1 output: the full plan, but NO code content. Code comes in Stage 2."""
    feature_name: str = Field(..., description="Short kebab-case name (e.g., 'login-validation')")
    branch_name: str = Field(..., description="Git branch name, format: 'auto/<jira-key>-<feature>'")
    pr_title: str = Field(..., description="Concise PR title")
    pr_body: str = Field(..., description="Markdown PR body explaining what was generated")
    files_to_create: list[FilePlan] = Field(..., min_length=1, description="Files to create or modify")
    notes: str = Field(default="", description="Caveats, assumptions, or items needing human attention")


class GeneratedFile(BaseModel):
    """A complete generated file (plan + content)."""
    file_path: str
    content: str
    is_new_file: bool = True
    purpose: str = ""


class CodeGenerationOutput(BaseModel):
    """Final output of Agent 2 after both stages complete."""
    feature_name: str
    branch_name: str
    pr_title: str
    pr_body: str
    files: list[GeneratedFile]
    notes: str = ""


# ─────────────────────────────────────────────────────────────
# Schemas for Agent 3 (Reviewer)
#
# Field names chosen to be unambiguous and LLM-friendly.
# Required boolean compliance flags ensure the LLM produces a
# complete checklist every time, not just a free-form list of issues.
#
# IMPORTANT: We deliberately do NOT use Pydantic's max_length on the
# `issues` list. While valid Python, it translates to a JSON schema
# `maxItems` constraint that some LLM providers' constrained-decoding
# engines cannot compile when the array contains complex objects.
#
# Instead, we cap and de-duplicate the issues list AFTER the LLM
# response in agent3_reviewer.py. This keeps the schema simple and
# provider-compatible while still preventing repetition collapse.
# ─────────────────────────────────────────────────────────────

class ReviewIssue(BaseModel):
    """A single issue found during code review."""
    severity: Literal["blocking", "major", "minor", "info"] = Field(
        ...,
        description="blocking=must fix before merge, major=important but not blocking, "
                    "minor=nice-to-have, info=FYI / observation"
    )
    file_path: str = Field(
        ...,
        description="Project-relative path of the file with the issue (e.g., 'tests/step_defs/test_login.py')"
    )
    line_number: Optional[int] = Field(
        default=None,
        description="Line number (1-indexed), or null if file-level issue with no specific line"
    )
    # DEFAULTED, not required (31 Jul 2026). A review came back with five
    # well-formed issues and this one enum omitted on every one of them;
    # because it was `...` the whole ReviewReport failed validation, Agent 3
    # crashed, and the tokens were spent for nothing. A category is the least
    # load-bearing field in the report - losing its precision costs far less
    # than losing the review. The repair attempt in llm_client.invoke_structured
    # asks for it properly first; this is the backstop behind that.
    issue_type: Literal["style", "functional_bug", "missing_coverage", "security", "best_practice"] = Field(
        default="best_practice",
        description="Category: style=formatting/naming, functional_bug=test will fail, "
                    "missing_coverage=test case not addressed, security=credentials/injection, "
                    "best_practice=could be cleaner. ALWAYS set this explicitly - "
                    "it defaults to best_practice only to stop an omission voiding the report."
    )
    description: str = Field(
        ...,
        description="What the issue is, in 1-2 sentences"
    )
    suggested_fix: str = Field(
        ...,
        description="How to fix it. Include corrected code snippet if helpful."
    )
    # Positive evidence for a stop. Defaulted so an older or partial report
    # still parses; agent3_reviewer.derive_verdict treats a missing one as
    # "no failure was found" for anything but a security finding.
    failure_scenario: str | None = Field(
        default=None,
        description="REQUIRED for severity=blocking and for issue_type=functional_bug: "
                    "the concrete scenario or step, the line that breaks, and what goes "
                    "wrong (the error raised or the wrong result). If, after checking, you "
                    "cannot name one because the code works, the finding is not blocking: "
                    "lower its severity or leave it out. The application is assumed to "
                    "behave as the test case says: 'if the app behaves differently, the "
                    "assertion fails' is the test doing its job, not a bug - never file it. "
                    "null for advisory findings."
    )
    # Which of the two ways a test can be wrong. They are refuted by different
    # evidence: a test predicted to FAIL that the runner just ran green on this
    # commit was not broken; a test that PASSES WRONGLY is untouched by a green
    # run, because passing is exactly its defect.
    test_outcome: Literal["fails", "passes_wrongly"] | None = Field(
        default=None,
        description="With failure_scenario: 'fails' when the test errors or its "
                    "assertion fails against an application behaving as the test case "
                    "says; 'passes_wrongly' when the test passes even though the "
                    "application is wrong (a vacuous or missing assertion). null when "
                    "there is no failure_scenario."
    )


class ReviewReport(BaseModel):
    """Output of Agent 3 (Reviewer) for one Pull Request."""
    pr_number: int = Field(..., description="The PR number being reviewed")
    overall_verdict: Literal["approve", "request_changes", "comment"] = Field(
        ...,
        description="approve=ready to merge, request_changes=blocking issues found, "
                    "comment=advisory only (minor or info issues)"
    )
    summary: str = Field(
        ...,
        description="2-3 sentence high-level summary of the review"
    )
    # NOTE: No max_length here — see module docstring for why.
    # Cap is enforced in agent3_reviewer.py post-processing.
    issues: list[ReviewIssue] = Field(
        default_factory=list,
        description="List of issues found. Empty list means no issues. "
                    "Be selective: report each distinct issue ONCE, max 10 total."
    )
    style_compliance: bool = Field(
        ...,
        description="Does the code follow the reference style (POM, naming, imports)?"
    )
    type_hints_present: bool = Field(
        ...,
        description="Are type hints used consistently on new function signatures?"
    )
    no_hardcoded_waits: bool = Field(
        ...,
        description="Code is free of time.sleep() and similar hardcoded waits?"
    )
    pom_compliant: bool = Field(
        ...,
        description=(
            "Selectors come from the app inventory via self.sel('<key>') — no "
            "raw selector literal in ANY file, page objects included?"
        )
    )
    coverage_complete: bool = Field(
        ...,
        description="All claimed test cases have corresponding Gherkin scenarios?"
    )


# ─────────────────────────────────────────────────────────────
# Schemas for Agent 5 (Reporter)
#
# Agent 5 reads JUnit XML produced by Agent 4 (Runner), summarizes results,
# and posts a friendly comment to the parent Jira story.
#
# IMPORTANT for LLM compatibility (lesson from Day 5):
#   - No max_length on lists (some providers can't compile maxItems)
#   - No regex patterns or format constraints on strings
#   - Quantity caps go in post-processing, not the schema
# ─────────────────────────────────────────────────────────────

class TestResult(BaseModel):
    """A single test case result parsed from JUnit XML.

    Note: this schema is NOT used as LLM structured output. It's a plain
    data model for Python code that parses JUnit XML. The LLM only sees
    the aggregated RunReport and produces JiraCommentDraft.
    """
    name: str = Field(..., description="Test method name (e.g., 'test_successful_login')")
    classname: str = Field(..., description="Module path (e.g., 'tests.step_defs.test_login')")
    status: Literal["passed", "failed", "error", "skipped"] = Field(
        ...,
        description="passed=test ran and asserted true, failed=assertion failed, "
                    "error=test setup/teardown crashed, skipped=intentionally not run"
    )
    duration_seconds: float = Field(default=0.0, description="How long the test took")
    failure_message: Optional[str] = Field(
        default=None,
        description="First line of the failure/error message; None if passed/skipped"
    )


class RunReport(BaseModel):
    """Aggregated test run summary parsed from JUnit XML.

    Built by Python code (not the LLM). Passed to the LLM as context
    so it can write a contextual comment.
    """
    total: int = Field(..., description="Total tests run")
    passed: int = Field(..., description="Tests that passed")
    failed: int = Field(..., description="Tests that failed (assertion errors)")
    errors: int = Field(default=0, description="Tests that errored (setup/teardown crashes)")
    skipped: int = Field(default=0, description="Tests intentionally skipped")
    duration_seconds: float = Field(default=0.0, description="Total run time")
    results: list[TestResult] = Field(default_factory=list, description="Per-test details")
    # Context that helps Agent 5 build a useful comment:
    pr_number: Optional[int] = Field(default=None, description="PR that triggered this run")
    pr_url: Optional[str] = Field(default=None, description="Link to the PR")
    workflow_run_url: Optional[str] = Field(default=None, description="Link to the GHA run")
    html_report_url: Optional[str] = Field(default=None, description="Link to pytest HTML report artifact")
    commit_sha: Optional[str] = Field(default=None, description="Commit SHA that was tested")


class JiraCommentDraft(BaseModel):
    """The LLM's output: a Jira comment ready to post.

    Why a structured output (not raw text):
      - Forces the LLM to give us exactly what we need
      - Title is useful for logs and audit trails
      - body_markdown is what gets posted; Jira renders Markdown via ADF
        (Atlassian Document Format) for newer Cloud APIs
    """
    title: str = Field(
        ...,
        description="One-line headline for logs (e.g., 'All 9 tests passed' or "
                    "'2 of 9 tests failed — login validation issues')"
    )
    body_markdown: str = Field(
        ...,
        description="The full comment to post on the Jira story, in Markdown. "
                    "Should include: pass/fail summary, link to PR, link to test report, "
                    "and (if any) brief notes on what failed."
    )