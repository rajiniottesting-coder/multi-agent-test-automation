"""
Pydantic schemas for data flowing between agents.
These are the contracts — every agent reads/writes data matching these shapes.
"""
from typing import Literal, Optional
from pydantic import BaseModel, Field


class TestStep(BaseModel):
    """A single step inside a test case."""
    step_number: int = Field(..., description="1-indexed step order")
    action: str = Field(..., description="What the user does (e.g., 'Click Login button')")
    expected_result: str = Field(..., description="What should happen (e.g., 'User is logged in')")


class TestCase(BaseModel):
    """A manual test case generated by Agent 1 (Analyst)."""
    title: str = Field(..., description="Concise test case title")
    description: str = Field(..., description="What this test verifies")
    priority: Literal["High", "Medium", "Low"] = Field(default="Medium")
    test_type: Literal["Positive", "Negative", "Edge"] = Field(default="Positive")
    preconditions: list[str] = Field(default_factory=list, description="Setup needed before test")
    steps: list[TestStep] = Field(..., description="Ordered test steps")
    expected_outcome: str = Field(..., description="Overall expected result")
    test_data: Optional[dict] = Field(default=None, description="Test data like usernames/passwords")


class TestCaseList(BaseModel):
    """A collection of test cases generated from one story."""
    story_summary: str = Field(..., description="Brief summary of the story analyzed")
    test_cases: list[TestCase] = Field(..., min_length=1, description="At least one test case")